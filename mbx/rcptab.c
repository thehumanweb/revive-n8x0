/* The significand's offset from trunc16(1/q): +1, 0 or -1 */
int rcp_offset(int m)
{
	int i = m - 32768;

	if (i < 0 || i > 32767)
		return 0;
	return (rcp_plus[i >> 5] >> (i & 31) & 1) - (int)(rcp_minus[i >> 5] >> (i & 31) & 1);
}
